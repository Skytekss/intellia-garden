import React from 'react';
import {
  Sparkles,
  ThermometerSnowflake,
  Truck,
  CalendarCheck,
  ArrowRight,
} from 'lucide-react';
import { motion } from 'motion/react';
import { NavigationTab } from '../../types';
import { useApp } from '../../context/AppContext';
import { getLocalizedRecommendations } from '../../context/localizedData';

interface ForecastRecommendationsProps {
  onNavigate?: (tab: NavigationTab) => void;
  className?: string;
}

const ICON_MAP: Record<string, React.ComponentType<{ className?: string }>> = {
  calendar: CalendarCheck,
  truck: Truck,
  sparkles: Sparkles,
};

export const ForecastRecommendations: React.FC<ForecastRecommendationsProps> = ({
  onNavigate,
  className = '',
}) => {
  const { isEnglish } = useApp();
  const recommendations = getLocalizedRecommendations(isEnglish);

  const storageAdvice = isEnglish
    ? [
        {
          title: 'Temperature regime',
          value: '+0.5°C … +1.5°C',
          detail: 'Prevents premature tissue respiration',
        },
        {
          title: 'Chamber relative humidity',
          value: '90 – 95%',
          detail: 'Minimizes shrinkage and weight loss of apples',
        },
        {
          title: 'Controlled Atmosphere (CA)',
          value: '1.2% O₂ / 1.0% CO₂',
          detail: 'Extends commercial storage lifespan to 7–9 months',
        },
      ]
    : [
        {
          title: 'Температурный режим',
          value: '+0.5°C … +1.5°C',
          detail: 'Предотвращает преждевременное дыхание тканей',
        },
        {
          title: 'Влажность воздуха в камере',
          value: '90 – 95%',
          detail: 'Минимизирует увядание и потерю веса яблок',
        },
        {
          title: 'Контролируемая атмосфера (CA)',
          value: '1.2% O₂ / 1.0% CO₂',
          detail: 'Увеличивает срок реализации до 7–9 месяцев',
        },
      ];

  return (
    <div
      data-testid="forecast-recommendations-panel"
      className={`space-y-4 sm:space-y-6 ${className}`}
    >
      {/* AI Recommendation Header */}
      <div className="bg-white rounded-2xl border border-slate-200/80 shadow-xs p-5 sm:p-6 flex flex-col md:flex-row items-start md:items-center justify-between gap-4">
        <div className="space-y-1">
          <div className="inline-flex items-center gap-2 px-2.5 py-1 rounded-full bg-purple-100 text-purple-800 text-xs font-semibold">
            <Sparkles className="w-3.5 h-3.5" />
            <span>{isEnglish ? 'AI Agro-Recommendations' : 'AI-Агрорекомендации'}</span>
          </div>
          <h3 className="text-lg font-bold text-slate-900 tracking-tight">
            {isEnglish
              ? 'Optimal Harvest & Logistics Schedule'
              : 'Оптимальный календарный план уборки и логистики'}
          </h3>
          <p className="text-xs sm:text-sm text-slate-500 max-w-2xl">
            {isEnglish
              ? 'Generated by neural network based on regional weather forecast, ripening dynamics, and flesh firmness laboratory analysis.'
              : 'Сформирован нейросетью на основе метеопрогноза Тульской области, динамики созревания и лабораторных анализов плотности мякоти.'}
          </p>
        </div>
      </div>

      {/* Recommendations Cards */}
      <div className="space-y-3 sm:space-y-4">
        {recommendations.map((rec, index) => {
          const Icon = ICON_MAP[rec.iconName] || Sparkles;
          return (
            <motion.div
              key={rec.id}
              initial={{ opacity: 0 }}
              animate={{ opacity: 1 }}
              transition={{ duration: 0.2, delay: index * 0.04 }}
              className="bg-white rounded-2xl border border-slate-200/80 shadow-xs p-5 hover:shadow-md transition-shadow duration-200"
            >
              <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-3">
                <div className="flex items-start gap-3.5">
                  <div className="w-10 h-10 rounded-xl bg-slate-50 text-slate-700 flex items-center justify-center shrink-0 border border-slate-200/80">
                    <Icon className="w-5 h-5 text-emerald-700" />
                  </div>
                  <div>
                    <div className="flex flex-wrap items-center gap-2 mb-1">
                      <span
                        className={`px-2.5 py-0.5 rounded-full text-xs font-semibold border ${rec.priorityColor}`}
                      >
                        {rec.priority}
                      </span>
                    </div>
                    <h4 className="text-sm sm:text-base font-bold text-slate-900">
                      {rec.title}
                    </h4>
                    <p className="text-xs sm:text-sm text-slate-600 mt-1 leading-relaxed">
                      {rec.description}
                    </p>
                  </div>
                </div>

                {onNavigate && (
                  <button
                    type="button"
                    onClick={() => onNavigate(rec.targetTab)}
                    className="self-start sm:self-center inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl border border-slate-200 text-xs font-semibold text-slate-700 hover:text-emerald-800 hover:border-emerald-300 hover:bg-slate-50 transition-colors cursor-pointer whitespace-nowrap"
                  >
                    <span>{rec.actionText}</span>
                    <ArrowRight className="w-3.5 h-3.5" />
                  </button>
                )}
              </div>
            </motion.div>
          );
        })}
      </div>

      {/* Storage & Post-Harvest Advice */}
      <div className="bg-white rounded-2xl border border-slate-200/80 shadow-xs p-5 sm:p-6">
        <div className="flex items-center gap-2 mb-4">
          <ThermometerSnowflake className="w-5 h-5 text-sky-600" />
          <h4 className="text-base font-bold text-slate-900">
            {isEnglish
              ? 'Post-Harvest Cold Storage Protocol (Refrigeration Chambers)'
              : 'Регламент закладки урожая на хранение (Холодильные камеры)'}
          </h4>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
          {storageAdvice.map((item, idx) => (
            <div
              key={idx}
              className="p-4 rounded-xl bg-slate-50 border border-slate-100 flex flex-col justify-between"
            >
              <div>
                <span className="text-xs text-slate-500 font-medium block">
                  {item.title}
                </span>
                <span className="text-base font-bold text-slate-900 mt-1 block">
                  {item.value}
                </span>
              </div>
              <span className="text-xs text-slate-400 mt-2 block">
                {item.detail}
              </span>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
};
